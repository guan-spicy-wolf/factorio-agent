"""The comparison table: ``compare/<set>.jsonl`` (one row per member, member order)
and ``compare/<set>.md`` (the header with the machine state, the hard-metric table
with the winner marked, every feasible member's render and contract).

The ``.md`` is for reading and choosing; the ``.jsonl`` is what a committed choice
points at (``blueprint_sha`` identifies the member's unit). Both are generated; do
not edit them by hand.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from fgen.compare.variants import VariantSet
from fgen.data.schema import GameData
from fgen.layout.render import LEGEND


def write(
    vset: VariantSet,
    rows: list[dict[str, Any]],
    meta: dict[str, Any],
    gd: GameData,
    out_dir: str | Path,
) -> tuple[Path, Path]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    jsonl = out / f"{vset.name}.jsonl"
    jsonl.write_text("".join(json.dumps(r, sort_keys=True) + "\n" for r in rows))
    md = out / f"{vset.name}.md"
    md.write_text("\n".join(render_md(vset, rows, meta, gd)) + "\n")
    return jsonl, md


def _cells(*xs: Any) -> str:
    return "| " + " | ".join(str(x) for x in xs) + " |"


def _g(x: Any, fmt: str = "{:g}") -> str:
    return "-" if x is None else fmt.format(x)


def render_md(
    vset: VariantSet, rows: list[dict[str, Any]], meta: dict[str, Any], gd: GameData
) -> list[str]:
    asked = vset.asked_by
    head = [
        f"# compare: {vset.name}",
        "",
        f"Generated by `uv run --extra solver fgen compare {vset.source or vset.name}`; do not "
        f"edit by hand. Family `{vset.family}`, game data {gd.source} {gd.version}. "
        f"{meta.get('members')} members in {meta.get('procs')} process(es) on "
        f"{meta.get('nproc')} cores, 1-minute load {meta.get('load_before')} -> "
        f"{meta.get('load_after')}, {meta.get('wall_s')} s wall. Rank: `{vset.rank}` "
        + (
            "(fewest seconds to the first period)."
            if vset.rank == "first"
            else f"(the `{vset.rank}` preset's terms over the period metrics; "
            "area alone for families without a period)."
        ),
    ]
    if asked:
        head += [
            "",
            "Question: "
            + (asked.get("question") or "-")
            + f" (asked by {asked.get('who', '-')}, {asked.get('date', '-')}).",
        ]
    base = ", ".join(f"{k}={v!r}" for k, v in sorted(vset.base.items()))
    head += ["", f"Base: `{base or '-'}`", ""]
    has_period = any(r.get("period") for r in rows)
    cols = ["rank", "variant", "status", "wall s"]
    if has_period:
        cols += [
            "first feasible s",
            "solve s (proven)",
            "periods",
            "period WxH",
            "poles/ins/pipes",
            "cost",
            "kinds",
        ]
    cols += ["unit area", "machines", "predicted/s", "blueprint", "reason / note"]
    lines = [*head, "## Members", "", _cells(*cols), _cells(*["---"] * len(cols))]
    for r in rows:
        status = r.get("status") or "-"
        rk = r.get("rank")
        cells: list[Any] = [
            "**1**" if rk == 1 else (rk or "-"),
            r["variant"],
            status,
            _g(r["wall_s"]),
        ]
        per, pred = r.get("period") or {}, r.get("predicted") or {}
        if has_period:
            mt = per.get("metrics") or {}
            if per:
                cells += [
                    _g(per.get("first_feasible_s"), "{:.1f}"),
                    f"{_g(per.get('seconds'), '{:.1f}')} ({'yes' if per.get('proven') else 'no'})",
                    _g(per.get("periods")),
                    f"{per.get('width')}x{per.get('height')}",
                    f"{per.get('poles')}/{per.get('inserters')}/{per.get('pipes') or 0}",
                    _g(mt.get("cost_units")),
                    _g(mt.get("kinds")),
                ]
            else:
                cells += ["-"] * 7
        cells += [
            _g(pred.get("area")),
            _g(pred.get("machines")),
            _g(pred.get("throughput"), "{:.4g}"),
            r.get("blueprint_sha") or "-",
            (r.get("reason") or r.get("note") or "")[:120],
        ]
        lines.append(_cells(*cells))
    lines += [""]
    w = meta.get("winner")
    if w:
        lines += [f"Winner by `{vset.rank}`: **{w}**.", ""]
    else:
        lines += ["No feasible member.", ""]
    inf = [r for r in rows if r.get("status") == "infeasible" and r.get("suggestions")]
    if inf:
        lines += ["## Suggestions on infeasible members", ""]
        for r in inf:
            lines.append(f"- `{r['variant']}`: " + "; ".join(f"`{s}`" for s in r["suggestions"]))
        lines.append("")
    oks = [r for r in rows if r.get("render")]
    if oks:
        lines += ["## Units", "", LEGEND + "  u pipe-to-ground", ""]
        for r in oks:
            lines += [
                f"### {r['variant']}",
                "",
                "```",
                r["render"],
                *r.get("interfaces", []),
                "```",
                "",
            ]
    return lines


__all__ = ["render_md", "write"]
